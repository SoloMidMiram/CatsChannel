"""Render and check generated project-context documents."""

from __future__ import annotations

import os
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any

from .context_store import CONTEXT_DIR, GENERATED_MARKER, ROOT, _is_remote, load_context


def _source_link(source: dict[str, Any], root: Path, output_directory: Path) -> str:
    locator = str(source["locator"])
    if _is_remote(locator):
        return f"[{source['title']}]({locator})"
    if source["kind"] == "code_revision":
        return f"{source['title']} (`{locator}`)"
    relative = os.path.relpath(root / locator, output_directory).replace(os.sep, "/")
    return f"[{source['title']}]({relative})"


def _latest_verification(records: list[dict[str, Any]]) -> str:
    return max(str(record["last_verified_at"]) for record in records)


def render_overview(
    root: Path,
    taxonomy: dict[str, Any],
    sources: list[dict[str, Any]],
    records: list[dict[str, Any]],
) -> str:
    """Generate the current narrative entirely from structured records."""
    source_by_id = {source["id"]: source for source in sources}
    output_directory = root / CONTEXT_DIR
    superseded = {
        record["supersedes"] for record in records if isinstance(record.get("supersedes"), str)
    }
    lines = [
        GENERATED_MARKER,
        "# Current project brief",
        "",
        (
            f"> Generated from {len(records)} records and {len(sources)} evidence sources; "
            f"latest verification: {_latest_verification(records)}. Current-state claims must "
            "still be checked against live code, tests, Git, or GitHub."
        ),
        "",
    ]
    for section in taxonomy["brief_sections"]:
        lines.extend((f"## {section['title']}", ""))
        selected = [
            record
            for record in records
            if record.get("brief", {}).get("section") == section["id"]
            and record.get("status") != "superseded"
            and record["id"] not in superseded
        ]
        selected.sort(key=lambda record: (-record["brief"]["priority"], record["id"]))
        if not selected:
            lines.extend(("No active records in this section.", ""))
            continue
        for record in selected:
            source = source_by_id[record["source"]]
            scope = f" Scope: {record['scope']}." if record.get("scope") else ""
            lines.append(
                f"- **{record['id']}** — {record['statement']} "
                f"_Status: {record['status']}; freshness: {record['freshness']}._"
                f"{scope} {_source_link(source, root, output_directory)}"
            )
        lines.append("")
    lines.extend(("## Record index", "", "| Kind | Count | Statuses |", "| --- | ---: | --- |"))
    for kind in taxonomy["record_kinds"]:
        kind_records = [record for record in records if record["kind"] == kind]
        statuses = Counter(record["status"] for record in kind_records)
        rendered_statuses = ", ".join(
            f"{status}: {count}" for status, count in sorted(statuses.items())
        )
        lines.append(f"| {kind} | {len(kind_records)} | {rendered_statuses or 'none'} |")
    lines.extend(
        (
            "",
            "## Inspect focused context",
            "",
            "```bash",
            'uv run --frozen python tools/project_context.py select "<question>"',
            "```",
            "",
            "Edit `records.jsonl` or `sources.jsonl`, then regenerate; do not edit this file.",
            "",
        )
    )
    return "\n".join(lines)


def render_decision(
    root: Path,
    record: dict[str, Any],
    source_by_id: dict[str, dict[str, Any]],
) -> str:
    output_directory = root / CONTEXT_DIR / "decisions"
    evidence_ids = list(dict.fromkeys([record["source"], *record["verified_against"]]))
    lines = [
        GENERATED_MARKER,
        f"# {record['id']}: {record['statement']}",
        "",
        f"- Status: `{record['status']}`",
        f"- Freshness: `{record['freshness']}`",
        f"- Area: `{record['area']}`",
        f"- Recorded: `{record['recorded_at']}`",
        f"- Last verified: `{record['last_verified_at']}`",
        f"- Tags: {', '.join(f'`{tag}`' for tag in record['tags'])}",
    ]
    if record.get("scope"):
        lines.append(f"- Scope: {record['scope']}")
    lines.extend(
        ("", "## Rationale and consequences", "", record["details"], "", "## Evidence", "")
    )
    for source_id in evidence_ids:
        source = source_by_id[source_id]
        lines.append(f"- `{source_id}` — {_source_link(source, root, output_directory)}")
    if record.get("supersedes"):
        lines.extend(("", f"Supersedes `{record['supersedes']}`."))
    lines.append("")
    return "\n".join(lines)


def generated_outputs(root: Path = ROOT) -> dict[Path, str]:
    taxonomy, sources, records = load_context(root)
    source_by_id = {source["id"]: source for source in sources}
    outputs = {CONTEXT_DIR / "overview.md": render_overview(root, taxonomy, sources, records)}
    for record in records:
        if record["kind"] == "decision" and record.get("details"):
            outputs[CONTEXT_DIR / "decisions" / f"{record['id']}.md"] = render_decision(
                root, record, source_by_id
            )
    return outputs


def check_generated(root: Path = ROOT) -> list[str]:
    expected = generated_outputs(root)
    errors: list[str] = []
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            errors.append(f"generated file missing: {relative}")
        elif path.read_text(encoding="utf-8") != content:
            errors.append(f"generated file is stale: {relative}")
    decisions = root / CONTEXT_DIR / "decisions"
    if decisions.is_dir():
        expected_decisions = {root / path for path in expected if path.parent.name == "decisions"}
        for path in decisions.glob("*.md"):
            if path not in expected_decisions:
                errors.append(f"unexpected generated decision file: {path.relative_to(root)}")
    return errors


def write_generated(root: Path = ROOT) -> list[Path]:
    written: list[Path] = []
    for relative, content in generated_outputs(root).items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                newline="\n",
                dir=path.parent,
                suffix=".tmp",
                delete=False,
            ) as stream:
                temporary = Path(stream.name)
                stream.write(content)
            os.replace(temporary, path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        written.append(relative)
    return written
