"""Load and validate auditable project-context records and local evidence."""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
from collections import Counter
from datetime import date
from pathlib import Path, PureWindowsPath
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CONTEXT_DIR = Path("project-context")
GENERATED_MARKER = "<!-- Generated by tools/project_context.py; do not edit. -->"

_RECORD_ID = re.compile(r"^(fact|decision|task|blocker|proposal)-[0-9]{3}$")
_SOURCE_ID = re.compile(r"^source-[0-9]{3}$")
_TAG = re.compile(r"^[a-z0-9][a-z0-9._-]*$")
_DATE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
_SENSITIVE_ASSIGNMENT = re.compile(
    r"(?i)(?:authorization|bot[_-]?token|api[_-]?hash|password|cookie|"
    r"proxy[_-]?(?:url|password)|secret|session[_-]?string)\s*[:=]\s*"
    r"(?:['\"])?[^\s'\"`]{12,}"
)

_RECORD_REQUIRED = {
    "id",
    "kind",
    "area",
    "tags",
    "statement",
    "status",
    "source",
    "recorded_at",
    "freshness",
    "last_verified_at",
    "verified_against",
    "supersedes",
}
_RECORD_ALLOWED = _RECORD_REQUIRED | {"scope", "details", "brief"}
_SOURCE_REQUIRED = {
    "id",
    "kind",
    "title",
    "locator",
    "captured_at",
    "freshness",
    "last_verified_at",
}
_SOURCE_ALLOWED = _SOURCE_REQUIRED | {"notes", "content_sha256"}
_MEMORY_TEXT_SUFFIXES = {".json", ".jsonl", ".md", ".yaml", ".yml"}
_SENSITIVE_LOCAL_ROOTS = {".env", ".secrets", ".runtime", ".cache", "library"}


class ContextDataError(ValueError):
    """Raised when a context source cannot be parsed."""


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise ContextDataError(f"{path.name}: cannot read valid UTF-8 JSON") from error
    if not isinstance(value, dict):
        raise ContextDataError(f"{path}: expected one JSON object")
    return value


def _load_jsonl(path: Path) -> list[dict[str, Any]]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeError) as error:
        raise ContextDataError(f"{path.name}: cannot read UTF-8 JSONL") from error
    values: list[dict[str, Any]] = []
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError as error:
            raise ContextDataError(f"{path}:{line_number}: {error}") from error
        if not isinstance(value, dict):
            raise ContextDataError(f"{path}:{line_number}: expected one JSON object")
        values.append(value)
    return values


def load_context(root: Path = ROOT) -> tuple[dict[str, Any], list[dict], list[dict]]:
    context = root / CONTEXT_DIR
    return (
        _load_json(context / "taxonomy.yaml"),
        _load_jsonl(context / "sources.jsonl"),
        _load_jsonl(context / "records.jsonl"),
    )


def _parse_date(value: object, field: str, owner: str, errors: list[str]) -> date | None:
    if not isinstance(value, str) or not _DATE.fullmatch(value):
        errors.append(f"{owner}: {field} must be an ISO date")
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        errors.append(f"{owner}: {field} is not a valid date")
        return None


def _validate_freshness(
    item: dict[str, Any],
    owner: str,
    taxonomy: dict[str, Any],
    today: date,
    errors: list[str],
) -> date | None:
    freshness = item.get("freshness")
    freshness_config = taxonomy.get("freshness", {})
    values = freshness_config.get("values", [])
    if freshness not in values:
        errors.append(f"{owner}: unknown freshness {freshness!r}")
    verified = _parse_date(item.get("last_verified_at"), "last_verified_at", owner, errors)
    if verified is not None and verified > today:
        errors.append(f"{owner}: last_verified_at cannot be in the future")
    if freshness == "current" and verified is not None:
        max_age = freshness_config.get("current_max_age_days")
        if not isinstance(max_age, int) or max_age < 1:
            errors.append("taxonomy: current_max_age_days must be a positive integer")
        elif (today - verified).days > max_age:
            errors.append(
                f"{owner}: current evidence expired {(today - verified).days} days after "
                f"verification (limit {max_age})"
            )
    return verified


def _is_remote(locator: str) -> bool:
    return locator.startswith(("https://", "http://"))


def _local_locator_error(root: Path, locator: str) -> str | None:
    path = Path(locator)
    if path.is_absolute() or PureWindowsPath(locator).is_absolute():
        return "local locator must be repository-relative"
    parts = path.parts
    if parts and (parts[0] in _SENSITIVE_LOCAL_ROOTS or parts[0].startswith(".venv")):
        return "local locator points at an excluded private/runtime path"
    try:
        (root / path).resolve().relative_to(root.resolve())
    except ValueError:
        return "local locator escapes the repository"
    return None


def _sensitive_memory_locations(root: Path) -> list[str]:
    context = root / CONTEXT_DIR
    if not context.is_dir():
        return []
    findings: list[str] = []
    for path in sorted(context.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in _MEMORY_TEXT_SUFFIXES:
            continue
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeError):
            relative = path.relative_to(root).as_posix()
            findings.append(f"{relative}: could not inspect text safely")
            continue
        for line_number, line in enumerate(lines, start=1):
            if _SENSITIVE_ASSIGNMENT.search(line):
                relative = path.relative_to(root).as_posix()
                findings.append(f"{relative}:{line_number}: secret-like assignment detected")
    return findings


def _validate_source(
    source: dict[str, Any],
    root: Path,
    taxonomy: dict[str, Any],
    today: date,
) -> list[str]:
    source_id = str(source.get("id", "<missing-source-id>"))
    errors: list[str] = []
    missing = _SOURCE_REQUIRED - source.keys()
    extra = source.keys() - _SOURCE_ALLOWED
    if missing:
        errors.append(f"{source_id}: missing fields {sorted(missing)}")
    if extra:
        errors.append(f"{source_id}: unknown fields {sorted(extra)}")
    if not _SOURCE_ID.fullmatch(source_id):
        errors.append(f"{source_id}: invalid source ID")
    if not isinstance(source.get("kind"), str) or source["kind"] not in taxonomy.get(
        "source_kinds", {}
    ):
        errors.append(f"{source_id}: unknown source kind {source.get('kind')!r}")
    if not isinstance(source.get("title"), str) or not source.get("title", "").strip():
        errors.append(f"{source_id}: title must be non-empty")
    locator = source.get("locator")
    if not isinstance(locator, str) or not locator.strip():
        errors.append(f"{source_id}: locator must be non-empty")
    elif _SENSITIVE_ASSIGNMENT.search(locator):
        errors.append(f"{source_id}: locator appears to contain a secret")
    elif not _is_remote(locator):
        if source.get("kind") == "code_revision":
            result = subprocess.run(
                ["git", "cat-file", "-e", f"{locator}^{{commit}}"],
                cwd=root,
                capture_output=True,
                check=False,
            )
            if result.returncode:
                errors.append(f"{source_id}: Git commit {locator!r} is unavailable")
        else:
            locator_error = _local_locator_error(root, locator)
            if locator_error:
                errors.append(f"{source_id}: {locator_error}")
            elif not (root / locator).is_file():
                errors.append(f"{source_id}: local evidence does not exist: {locator}")
    captured = _parse_date(source.get("captured_at"), "captured_at", source_id, errors)
    digest = source.get("content_sha256")
    if digest is not None:
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            errors.append(f"{source_id}: content_sha256 must be lowercase SHA-256")
        elif (
            not isinstance(locator, str)
            or _is_remote(locator)
            or source.get("kind") == "code_revision"
        ):
            errors.append(f"{source_id}: content_sha256 requires a local text receipt")
        elif _local_locator_error(root, locator) is None and (root / locator).is_file():
            try:
                content = (root / locator).read_text(encoding="utf-8").encode("utf-8")
                if hashlib.sha256(content).hexdigest() != digest:
                    errors.append(f"{source_id}: local receipt content_sha256 mismatch")
            except (OSError, UnicodeError):
                errors.append(f"{source_id}: local receipt cannot be read safely")
    verified = _validate_freshness(source, source_id, taxonomy, today, errors)
    if captured is not None and captured > today:
        errors.append(f"{source_id}: captured_at cannot be in the future")
    if captured is not None and verified is not None and verified < captured:
        errors.append(f"{source_id}: last_verified_at cannot precede captured_at")
    return errors


def _validate_record(
    record: dict[str, Any],
    source_ids: set[str],
    taxonomy: dict[str, Any],
    today: date,
) -> list[str]:
    record_id = str(record.get("id", "<missing-record-id>"))
    errors: list[str] = []
    missing = _RECORD_REQUIRED - record.keys()
    extra = record.keys() - _RECORD_ALLOWED
    if missing:
        errors.append(f"{record_id}: missing fields {sorted(missing)}")
    if extra:
        errors.append(f"{record_id}: unknown fields {sorted(extra)}")
    match = _RECORD_ID.fullmatch(record_id)
    kind = record.get("kind")
    if match is None or match.group(1) != kind:
        errors.append(f"{record_id}: ID prefix must match kind {kind!r}")
    kind_config = taxonomy.get("record_kinds", {}).get(kind) if isinstance(kind, str) else None
    if not isinstance(kind_config, dict):
        errors.append(f"{record_id}: unknown record kind {kind!r}")
    elif record.get("status") not in kind_config.get("statuses", []):
        errors.append(f"{record_id}: status {record.get('status')!r} is invalid for {kind}")
    if record.get("area") not in taxonomy.get("areas", []):
        errors.append(f"{record_id}: unknown area {record.get('area')!r}")
    tags = record.get("tags")
    if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in tags):
        errors.append(f"{record_id}: tags must be a string list")
    elif len(tags) != len(set(tags)) or any(not _TAG.fullmatch(tag) for tag in tags):
        errors.append(f"{record_id}: tags must be unique lowercase tokens")
    statement = record.get("statement")
    if not isinstance(statement, str) or not statement.strip():
        errors.append(f"{record_id}: statement must be non-empty")
    elif "\n" in statement:
        errors.append(f"{record_id}: statement must stay on one logical line")
    elif _SENSITIVE_ASSIGNMENT.search(statement):
        errors.append(f"{record_id}: statement appears to contain a secret")
    if not isinstance(record.get("source"), str) or record["source"] not in source_ids:
        errors.append(f"{record_id}: source {record.get('source')!r} is not cataloged")
    verified_against = record.get("verified_against")
    if (
        not isinstance(verified_against, list)
        or not verified_against
        or not all(isinstance(item, str) for item in verified_against)
    ):
        errors.append(f"{record_id}: verified_against must be a non-empty list")
    elif len(verified_against) != len(set(verified_against)):
        errors.append(f"{record_id}: verified_against entries must be unique")
    else:
        missing_sources = sorted(set(verified_against) - source_ids)
        if missing_sources:
            errors.append(f"{record_id}: unknown verification sources {missing_sources}")
    recorded = _parse_date(record.get("recorded_at"), "recorded_at", record_id, errors)
    verified = _validate_freshness(record, record_id, taxonomy, today, errors)
    if recorded is not None and recorded > today:
        errors.append(f"{record_id}: recorded_at cannot be in the future")
    if recorded is not None and verified is not None and verified < recorded:
        errors.append(f"{record_id}: last_verified_at cannot precede recorded_at")
    supersedes = record.get("supersedes")
    if supersedes is not None and not isinstance(supersedes, str):
        errors.append(f"{record_id}: supersedes must be a record ID or null")
    brief = record.get("brief")
    if brief is not None:
        sections = {section.get("id") for section in taxonomy.get("brief_sections", [])}
        if not isinstance(brief, dict) or set(brief) != {"section", "priority"}:
            errors.append(f"{record_id}: brief requires only section and priority")
        elif not isinstance(brief.get("section"), str) or brief["section"] not in sections:
            errors.append(f"{record_id}: unknown brief section {brief.get('section')!r}")
        elif not isinstance(brief.get("priority"), int) or not 0 <= brief["priority"] <= 100:
            errors.append(f"{record_id}: brief priority must be between 0 and 100")
    return errors


def _supersession_cycles(records: list[dict[str, Any]]) -> list[list[str]]:
    """Find directed cycles iteratively, including cycles reached through a tail."""
    links = {
        record["id"]: record["supersedes"]
        for record in records
        if isinstance(record.get("id"), str) and isinstance(record.get("supersedes"), str)
    }
    visited: set[str] = set()
    cycles: list[list[str]] = []
    for start in sorted(links):
        path: list[str] = []
        positions: dict[str, int] = {}
        node = start
        while node in links and node not in visited:
            if node in positions:
                cycle = path[positions[node] :]
                if len(cycle) > 1:  # Self-supersession already has its own diagnostic.
                    cycles.append(sorted(cycle))
                break
            positions[node] = len(path)
            path.append(node)
            node = links[node]
        visited.update(path)
    return cycles


def validate_repository(root: Path = ROOT, *, today: date | None = None) -> list[str]:
    """Return every deterministic validation problem without contacting a service."""
    today = today or date.today()
    try:
        taxonomy, sources, records = load_context(root)
    except ContextDataError as error:
        return [str(error)]
    errors: list[str] = []
    if taxonomy.get("schema_version") != 1:
        errors.append("taxonomy: schema_version must be 1")
    source_ids = [str(source.get("id", "")) for source in sources]
    duplicate_sources = sorted(item for item, count in Counter(source_ids).items() if count > 1)
    if duplicate_sources:
        errors.append(f"sources: duplicate IDs {duplicate_sources}")
    for source in sources:
        errors.extend(_validate_source(source, root, taxonomy, today))
    record_ids = [str(record.get("id", "")) for record in records]
    duplicate_records = sorted(item for item, count in Counter(record_ids).items() if count > 1)
    if duplicate_records:
        errors.append(f"records: duplicate IDs {duplicate_records}")
    known_sources = set(source_ids)
    source_by_id = {source["id"]: source for source in sources if "id" in source}
    known_records = set(record_ids)
    for record in records:
        errors.extend(_validate_record(record, known_sources, taxonomy, today))
        if record.get("freshness") == "current":
            references = record.get("verified_against", [])
            if isinstance(references, list):
                for reference in [record.get("source"), *references]:
                    if (
                        isinstance(reference, str)
                        and reference in source_by_id
                        and source_by_id[reference].get("freshness") in {"stale", "unknown"}
                    ):
                        errors.append(
                            f"{record.get('id')}: current claim depends on {reference} "
                            "with stale/unknown evidence"
                        )
        supersedes = record.get("supersedes")
        if isinstance(supersedes, str):
            if supersedes not in known_records:
                errors.append(f"{record.get('id')}: supersedes unknown record {supersedes}")
            elif supersedes == record.get("id"):
                errors.append(f"{record.get('id')}: cannot supersede itself")
    errors.extend(
        f"records: supersession cycle: {', '.join(cycle)}"
        for cycle in _supersession_cycles(records)
    )
    for schema in ("record.schema.json", "source.schema.json"):
        if not (root / CONTEXT_DIR / "schema" / schema).is_file():
            errors.append(f"schema: missing {schema}")
    errors.extend(_sensitive_memory_locations(root))
    return errors
