"""Validate, generate, and select CatsChannel's auditable project context."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CONTEXT_DIR = Path("project-context")
GENERATED_MARKER = "<!-- Generated by tools/project_context.py; do not edit. -->"

_RECORD_ID = re.compile(r"^(fact|decision|task|blocker|proposal)-[0-9]{3}$")
_SOURCE_ID = re.compile(r"^source-[0-9]{3}$")
_TAG = re.compile(r"^[a-z0-9][a-z0-9._-]*$")
_TOKEN = re.compile(r"[a-z0-9]+")
_DATE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
_SENSITIVE_ASSIGNMENT = re.compile(
    r"(?i)(?:authorization|bot[_-]?token|api[_-]?hash|password|cookie|"
    r"proxy[_-]?(?:url|password)|secret|session[_-]?string)\s*[:=]\s*"
    r"(?:['\"])?[^\s'\"`]{12,}"
)

_RECORD_REQUIRED = {
    "id",
    "kind",
    "area",
    "tags",
    "statement",
    "status",
    "source",
    "recorded_at",
    "freshness",
    "last_verified_at",
    "verified_against",
    "supersedes",
}
_RECORD_ALLOWED = _RECORD_REQUIRED | {"scope", "details", "brief"}
_SOURCE_REQUIRED = {
    "id",
    "kind",
    "title",
    "locator",
    "captured_at",
    "freshness",
    "last_verified_at",
}
_SOURCE_ALLOWED = _SOURCE_REQUIRED | {"notes"}
_MEMORY_TEXT_SUFFIXES = {".json", ".jsonl", ".md", ".yaml", ".yml"}
_SENSITIVE_LOCAL_ROOTS = {".env", ".secrets", "library"}


class ContextDataError(ValueError):
    """Raised when a context source cannot be parsed."""


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ContextDataError(f"{path}: {error}") from error
    if not isinstance(value, dict):
        raise ContextDataError(f"{path}: expected one JSON object")
    return value


def _load_jsonl(path: Path) -> list[dict[str, Any]]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as error:
        raise ContextDataError(f"{path}: {error}") from error
    values: list[dict[str, Any]] = []
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError as error:
            raise ContextDataError(f"{path}:{line_number}: {error}") from error
        if not isinstance(value, dict):
            raise ContextDataError(f"{path}:{line_number}: expected one JSON object")
        values.append(value)
    return values


def load_context(root: Path = ROOT) -> tuple[dict[str, Any], list[dict], list[dict]]:
    context = root / CONTEXT_DIR
    return (
        _load_json(context / "taxonomy.yaml"),
        _load_jsonl(context / "sources.jsonl"),
        _load_jsonl(context / "records.jsonl"),
    )


def _parse_date(value: object, field: str, owner: str, errors: list[str]) -> date | None:
    if not isinstance(value, str) or not _DATE.fullmatch(value):
        errors.append(f"{owner}: {field} must be an ISO date")
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        errors.append(f"{owner}: {field} is not a valid date")
        return None


def _validate_freshness(
    item: dict[str, Any],
    owner: str,
    taxonomy: dict[str, Any],
    today: date,
    errors: list[str],
) -> date | None:
    freshness = item.get("freshness")
    freshness_config = taxonomy.get("freshness", {})
    values = freshness_config.get("values", [])
    if freshness not in values:
        errors.append(f"{owner}: unknown freshness {freshness!r}")
    verified = _parse_date(item.get("last_verified_at"), "last_verified_at", owner, errors)
    if verified is not None and verified > today:
        errors.append(f"{owner}: last_verified_at cannot be in the future")
    if freshness == "current" and verified is not None:
        max_age = freshness_config.get("current_max_age_days")
        if not isinstance(max_age, int) or max_age < 1:
            errors.append("taxonomy: current_max_age_days must be a positive integer")
        elif (today - verified).days > max_age:
            errors.append(
                f"{owner}: current evidence expired {(today - verified).days} days after "
                f"verification (limit {max_age})"
            )
    return verified


def _is_remote(locator: str) -> bool:
    return locator.startswith(("https://", "http://"))


def _local_locator_error(root: Path, locator: str) -> str | None:
    path = Path(locator)
    if path.is_absolute():
        return "local locator must be repository-relative"
    parts = path.parts
    if parts and (parts[0] in _SENSITIVE_LOCAL_ROOTS or parts[0].startswith(".venv")):
        return "local locator points at an excluded private/runtime path"
    try:
        (root / path).resolve().relative_to(root.resolve())
    except ValueError:
        return "local locator escapes the repository"
    return None


def _sensitive_memory_locations(root: Path) -> list[str]:
    context = root / CONTEXT_DIR
    if not context.is_dir():
        return []
    findings: list[str] = []
    for path in sorted(context.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in _MEMORY_TEXT_SUFFIXES:
            continue
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeError):
            relative = path.relative_to(root).as_posix()
            findings.append(f"{relative}: could not inspect text safely")
            continue
        for line_number, line in enumerate(lines, start=1):
            if _SENSITIVE_ASSIGNMENT.search(line):
                relative = path.relative_to(root).as_posix()
                findings.append(f"{relative}:{line_number}: secret-like assignment detected")
    return findings


def _validate_source(
    source: dict[str, Any],
    root: Path,
    taxonomy: dict[str, Any],
    today: date,
) -> list[str]:
    source_id = str(source.get("id", "<missing-source-id>"))
    errors: list[str] = []
    missing = _SOURCE_REQUIRED - source.keys()
    extra = source.keys() - _SOURCE_ALLOWED
    if missing:
        errors.append(f"{source_id}: missing fields {sorted(missing)}")
    if extra:
        errors.append(f"{source_id}: unknown fields {sorted(extra)}")
    if not _SOURCE_ID.fullmatch(source_id):
        errors.append(f"{source_id}: invalid source ID")
    if source.get("kind") not in taxonomy.get("source_kinds", {}):
        errors.append(f"{source_id}: unknown source kind {source.get('kind')!r}")
    if not isinstance(source.get("title"), str) or not source.get("title", "").strip():
        errors.append(f"{source_id}: title must be non-empty")
    locator = source.get("locator")
    if not isinstance(locator, str) or not locator.strip():
        errors.append(f"{source_id}: locator must be non-empty")
    elif _SENSITIVE_ASSIGNMENT.search(locator):
        errors.append(f"{source_id}: locator appears to contain a secret")
    elif not _is_remote(locator):
        if source.get("kind") == "code_revision":
            result = subprocess.run(
                ["git", "cat-file", "-e", f"{locator}^{{commit}}"],
                cwd=root,
                capture_output=True,
                check=False,
            )
            if result.returncode:
                errors.append(f"{source_id}: Git commit {locator!r} is unavailable")
        else:
            locator_error = _local_locator_error(root, locator)
            if locator_error:
                errors.append(f"{source_id}: {locator_error}")
            elif not (root / locator).is_file():
                errors.append(f"{source_id}: local evidence does not exist: {locator}")
    captured = _parse_date(source.get("captured_at"), "captured_at", source_id, errors)
    verified = _validate_freshness(source, source_id, taxonomy, today, errors)
    if captured is not None and captured > today:
        errors.append(f"{source_id}: captured_at cannot be in the future")
    if captured is not None and verified is not None and verified < captured:
        errors.append(f"{source_id}: last_verified_at cannot precede captured_at")
    return errors


def _validate_record(
    record: dict[str, Any],
    source_ids: set[str],
    taxonomy: dict[str, Any],
    today: date,
) -> list[str]:
    record_id = str(record.get("id", "<missing-record-id>"))
    errors: list[str] = []
    missing = _RECORD_REQUIRED - record.keys()
    extra = record.keys() - _RECORD_ALLOWED
    if missing:
        errors.append(f"{record_id}: missing fields {sorted(missing)}")
    if extra:
        errors.append(f"{record_id}: unknown fields {sorted(extra)}")
    match = _RECORD_ID.fullmatch(record_id)
    kind = record.get("kind")
    if match is None or match.group(1) != kind:
        errors.append(f"{record_id}: ID prefix must match kind {kind!r}")
    kind_config = taxonomy.get("record_kinds", {}).get(kind)
    if not isinstance(kind_config, dict):
        errors.append(f"{record_id}: unknown record kind {kind!r}")
    elif record.get("status") not in kind_config.get("statuses", []):
        errors.append(f"{record_id}: status {record.get('status')!r} is invalid for {kind}")
    if record.get("area") not in taxonomy.get("areas", []):
        errors.append(f"{record_id}: unknown area {record.get('area')!r}")
    tags = record.get("tags")
    if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in tags):
        errors.append(f"{record_id}: tags must be a string list")
    elif len(tags) != len(set(tags)) or any(not _TAG.fullmatch(tag) for tag in tags):
        errors.append(f"{record_id}: tags must be unique lowercase tokens")
    statement = record.get("statement")
    if not isinstance(statement, str) or not statement.strip():
        errors.append(f"{record_id}: statement must be non-empty")
    elif "\n" in statement:
        errors.append(f"{record_id}: statement must stay on one logical line")
    elif _SENSITIVE_ASSIGNMENT.search(statement):
        errors.append(f"{record_id}: statement appears to contain a secret")
    if record.get("source") not in source_ids:
        errors.append(f"{record_id}: source {record.get('source')!r} is not cataloged")
    verified_against = record.get("verified_against")
    if not isinstance(verified_against, list) or not verified_against:
        errors.append(f"{record_id}: verified_against must be a non-empty list")
    elif len(verified_against) != len(set(verified_against)):
        errors.append(f"{record_id}: verified_against entries must be unique")
    else:
        missing_sources = sorted(set(verified_against) - source_ids)
        if missing_sources:
            errors.append(f"{record_id}: unknown verification sources {missing_sources}")
    recorded = _parse_date(record.get("recorded_at"), "recorded_at", record_id, errors)
    verified = _validate_freshness(record, record_id, taxonomy, today, errors)
    if recorded is not None and recorded > today:
        errors.append(f"{record_id}: recorded_at cannot be in the future")
    if recorded is not None and verified is not None and verified < recorded:
        errors.append(f"{record_id}: last_verified_at cannot precede recorded_at")
    supersedes = record.get("supersedes")
    if supersedes is not None and not isinstance(supersedes, str):
        errors.append(f"{record_id}: supersedes must be a record ID or null")
    brief = record.get("brief")
    if brief is not None:
        sections = {section.get("id") for section in taxonomy.get("brief_sections", [])}
        if not isinstance(brief, dict) or set(brief) != {"section", "priority"}:
            errors.append(f"{record_id}: brief requires only section and priority")
        elif brief.get("section") not in sections:
            errors.append(f"{record_id}: unknown brief section {brief.get('section')!r}")
        elif not isinstance(brief.get("priority"), int) or not 0 <= brief["priority"] <= 100:
            errors.append(f"{record_id}: brief priority must be between 0 and 100")
    return errors


def validate_repository(root: Path = ROOT, *, today: date | None = None) -> list[str]:
    """Return every deterministic validation problem without contacting a service."""
    today = today or date.today()
    try:
        taxonomy, sources, records = load_context(root)
    except ContextDataError as error:
        return [str(error)]
    errors: list[str] = []
    if taxonomy.get("schema_version") != 1:
        errors.append("taxonomy: schema_version must be 1")
    source_ids = [str(source.get("id", "")) for source in sources]
    duplicate_sources = sorted(item for item, count in Counter(source_ids).items() if count > 1)
    if duplicate_sources:
        errors.append(f"sources: duplicate IDs {duplicate_sources}")
    for source in sources:
        errors.extend(_validate_source(source, root, taxonomy, today))
    record_ids = [str(record.get("id", "")) for record in records]
    duplicate_records = sorted(item for item, count in Counter(record_ids).items() if count > 1)
    if duplicate_records:
        errors.append(f"records: duplicate IDs {duplicate_records}")
    known_sources = set(source_ids)
    known_records = set(record_ids)
    for record in records:
        errors.extend(_validate_record(record, known_sources, taxonomy, today))
        supersedes = record.get("supersedes")
        if isinstance(supersedes, str):
            if supersedes not in known_records:
                errors.append(f"{record.get('id')}: supersedes unknown record {supersedes}")
            elif supersedes == record.get("id"):
                errors.append(f"{record.get('id')}: cannot supersede itself")
    for schema in ("record.schema.json", "source.schema.json"):
        if not (root / CONTEXT_DIR / "schema" / schema).is_file():
            errors.append(f"schema: missing {schema}")
    errors.extend(_sensitive_memory_locations(root))
    return errors


def _source_link(source: dict[str, Any], root: Path, output_directory: Path) -> str:
    locator = str(source["locator"])
    if _is_remote(locator):
        return f"[{source['title']}]({locator})"
    if source["kind"] == "code_revision":
        return f"{source['title']} (`{locator}`)"
    relative = os.path.relpath(root / locator, output_directory).replace(os.sep, "/")
    return f"[{source['title']}]({relative})"


def _latest_verification(records: list[dict[str, Any]]) -> str:
    return max(str(record["last_verified_at"]) for record in records)


def render_overview(
    root: Path,
    taxonomy: dict[str, Any],
    sources: list[dict[str, Any]],
    records: list[dict[str, Any]],
) -> str:
    """Generate the current narrative entirely from structured records."""
    source_by_id = {source["id"]: source for source in sources}
    output_directory = root / CONTEXT_DIR
    superseded = {
        record["supersedes"] for record in records if isinstance(record.get("supersedes"), str)
    }
    lines = [
        GENERATED_MARKER,
        "# Current project brief",
        "",
        (
            f"> Generated from {len(records)} records and {len(sources)} evidence sources; "
            f"latest verification: {_latest_verification(records)}. Current-state claims must "
            "still be checked against live code, tests, Git, or GitHub."
        ),
        "",
    ]
    for section in taxonomy["brief_sections"]:
        lines.extend((f"## {section['title']}", ""))
        selected = [
            record
            for record in records
            if record.get("brief", {}).get("section") == section["id"]
            and record.get("status") != "superseded"
            and record["id"] not in superseded
        ]
        selected.sort(key=lambda record: (-record["brief"]["priority"], record["id"]))
        if not selected:
            lines.extend(("No active records in this section.", ""))
            continue
        for record in selected:
            source = source_by_id[record["source"]]
            scope = f" Scope: {record['scope']}." if record.get("scope") else ""
            lines.append(
                f"- **{record['id']}** — {record['statement']} "
                f"_Status: {record['status']}; freshness: {record['freshness']}._"
                f"{scope} {_source_link(source, root, output_directory)}"
            )
        lines.append("")
    lines.extend(("## Record index", "", "| Kind | Count | Statuses |", "| --- | ---: | --- |"))
    for kind in taxonomy["record_kinds"]:
        kind_records = [record for record in records if record["kind"] == kind]
        statuses = Counter(record["status"] for record in kind_records)
        rendered_statuses = ", ".join(
            f"{status}: {count}" for status, count in sorted(statuses.items())
        )
        lines.append(f"| {kind} | {len(kind_records)} | {rendered_statuses or 'none'} |")
    lines.extend(
        (
            "",
            "## Inspect focused context",
            "",
            "```bash",
            'uv run --frozen python tools/project_context.py select "<question>"',
            "```",
            "",
            "Edit `records.jsonl` or `sources.jsonl`, then regenerate; do not edit this file.",
            "",
        )
    )
    return "\n".join(lines)


def render_decision(
    root: Path,
    record: dict[str, Any],
    source_by_id: dict[str, dict[str, Any]],
) -> str:
    output_directory = root / CONTEXT_DIR / "decisions"
    evidence_ids = list(dict.fromkeys([record["source"], *record["verified_against"]]))
    lines = [
        GENERATED_MARKER,
        f"# {record['id']}: {record['statement']}",
        "",
        f"- Status: `{record['status']}`",
        f"- Freshness: `{record['freshness']}`",
        f"- Area: `{record['area']}`",
        f"- Recorded: `{record['recorded_at']}`",
        f"- Last verified: `{record['last_verified_at']}`",
        f"- Tags: {', '.join(f'`{tag}`' for tag in record['tags'])}",
    ]
    if record.get("scope"):
        lines.append(f"- Scope: {record['scope']}")
    lines.extend(
        ("", "## Rationale and consequences", "", record["details"], "", "## Evidence", "")
    )
    for source_id in evidence_ids:
        source = source_by_id[source_id]
        lines.append(f"- `{source_id}` — {_source_link(source, root, output_directory)}")
    if record.get("supersedes"):
        lines.extend(("", f"Supersedes `{record['supersedes']}`."))
    lines.append("")
    return "\n".join(lines)


def generated_outputs(root: Path = ROOT) -> dict[Path, str]:
    taxonomy, sources, records = load_context(root)
    source_by_id = {source["id"]: source for source in sources}
    outputs = {CONTEXT_DIR / "overview.md": render_overview(root, taxonomy, sources, records)}
    for record in records:
        if record["kind"] == "decision" and record.get("details"):
            outputs[CONTEXT_DIR / "decisions" / f"{record['id']}.md"] = render_decision(
                root, record, source_by_id
            )
    return outputs


def check_generated(root: Path = ROOT) -> list[str]:
    expected = generated_outputs(root)
    errors: list[str] = []
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            errors.append(f"generated file missing: {relative}")
        elif path.read_text(encoding="utf-8") != content:
            errors.append(f"generated file is stale: {relative}")
    decisions = root / CONTEXT_DIR / "decisions"
    if decisions.is_dir():
        expected_decisions = {root / path for path in expected if path.parent.name == "decisions"}
        for path in decisions.glob("*.md"):
            if path not in expected_decisions:
                errors.append(f"unexpected generated decision file: {path.relative_to(root)}")
    return errors


def write_generated(root: Path = ROOT) -> list[Path]:
    written: list[Path] = []
    for relative, content in generated_outputs(root).items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(relative)
    return written


def _tokens(value: object) -> set[str]:
    return set(_TOKEN.findall(str(value).lower()))


def select_records(
    records: list[dict[str, Any]],
    sources: list[dict[str, Any]],
    query: str,
    *,
    kinds: set[str] | None = None,
    areas: set[str] | None = None,
    max_records: int = 8,
) -> list[tuple[int, dict[str, Any]]]:
    """Keyword/tag retrieval with deduplication and deterministic reranking."""
    query_tokens = _tokens(query)
    if not query_tokens:
        return []
    source_by_id = {source["id"]: source for source in sources}
    superseded = {
        record["supersedes"] for record in records if isinstance(record.get("supersedes"), str)
    }
    ranked: list[tuple[int, dict[str, Any]]] = []
    for record in records:
        if record["id"] in superseded or record["status"] == "superseded":
            continue
        if kinds and record["kind"] not in kinds:
            continue
        if areas and record["area"] not in areas:
            continue
        tag_tokens = set(record["tags"])
        categorical_tokens = _tokens(
            f"{record['kind']} {record['area']} {record['status']} {record.get('scope', '')}"
        )
        statement_tokens = _tokens(record["statement"])
        detail_tokens = _tokens(record.get("details", ""))
        source_tokens = _tokens(source_by_id[record["source"]]["title"])
        score = 0
        score += 10 * len(query_tokens & tag_tokens)
        score += 6 * len(query_tokens & categorical_tokens)
        score += 4 * len(query_tokens & statement_tokens)
        score += 2 * len(query_tokens & detail_tokens)
        score += len(query_tokens & source_tokens)
        if query.lower().strip() in record["statement"].lower():
            score += 12
        if score == 0:
            continue
        score += {"current": 3, "stable": 2, "historical": 0, "stale": -3}.get(
            record["freshness"], -1
        )
        if record["status"] in {
            "open",
            "pending",
            "in_progress",
            "blocked",
            "proposed",
        } and query_tokens & {"block", "blocking", "next", "pending", "unresolved"}:
            score += 5
        ranked.append((score, record))
    ranked.sort(
        key=lambda item: (
            -item[0],
            -item[1].get("brief", {}).get("priority", 0),
            item[1]["id"],
        )
    )
    deduplicated: list[tuple[int, dict[str, Any]]] = []
    seen_statements: set[str] = set()
    for item in ranked:
        normalized_statement = " ".join(item[1]["statement"].lower().split())
        if normalized_statement in seen_statements:
            continue
        deduplicated.append(item)
        seen_statements.add(normalized_statement)
    return deduplicated[:max_records]


def render_selection(
    query: str,
    selected: list[tuple[int, dict[str, Any]]],
    sources: list[dict[str, Any]],
    *,
    include_details: bool,
    max_chars: int,
) -> str:
    source_by_id = {source["id"]: source for source in sources}
    header = f"# Selected project context\n\nQuery: {query}\n"
    if not selected:
        return f"{header}\nNo matching records.\n"
    chunks: list[str] = []
    length = len(header) + 1
    for score, record in selected:
        source = source_by_id[record["source"]]
        lines = [
            f"## {record['id']} ({record['kind']} / {record['area']}; score {score})",
            "",
            f"- Statement: {record['statement']}",
            f"- Status: {record['status']}",
            f"- Freshness: {record['freshness']} (verified {record['last_verified_at']})",
            f"- Source: {record['source']} — {source['title']} — {source['locator']}",
            f"- Verified against: {', '.join(record['verified_against'])}",
        ]
        if record.get("scope"):
            lines.append(f"- Scope: {record['scope']}")
        base = "\n".join(lines) + "\n"
        detailed = base
        if include_details and record.get("details"):
            detailed += f"- Details: {record['details']}\n"
        chunk = detailed if length + len(detailed) <= max_chars else base
        if length + len(chunk) > max_chars:
            continue
        chunks.append(chunk)
        length += len(chunk) + 1
    if not chunks:
        return f"{header}\nNo record fits the requested context budget.\n"
    return f"{header}\n" + "\n".join(chunks)


def _print_errors(errors: list[str]) -> None:
    for error in errors:
        print(f"ERROR: {error}", file=sys.stderr)


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    actions = parser.add_subparsers(dest="action", required=True)
    actions.add_parser("validate", help="validate taxonomy, sources, records, and evidence")
    generate = actions.add_parser("generate", help="write or check generated context")
    generate.add_argument("--check", action="store_true")
    select = actions.add_parser("select", help="select compact context for a question")
    select.add_argument("query")
    select.add_argument("--kind", action="append", dest="kinds")
    select.add_argument("--area", action="append", dest="areas")
    select.add_argument("--max-records", type=int, default=8)
    select.add_argument("--max-chars", type=int, default=6000)
    select.add_argument("--include-details", action="store_true")
    select.add_argument("--json", action="store_true", dest="as_json")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    root = args.root.resolve()
    errors = validate_repository(root)
    if errors:
        _print_errors(errors)
        return 1
    _taxonomy, sources, records = load_context(root)
    if args.action == "validate":
        print(f"Validated {len(records)} records and {len(sources)} evidence sources.")
        return 0
    if args.action == "generate":
        if args.check:
            generated_errors = check_generated(root)
            if generated_errors:
                _print_errors(generated_errors)
                return 1
            print("Generated project context is current.")
        else:
            written = write_generated(root)
            print(f"Generated {len(written)} project-context files.")
        return 0
    if args.max_records < 1 or args.max_chars < 300:
        print(
            "ERROR: max-records must be positive and max-chars must be at least 300",
            file=sys.stderr,
        )
        return 2
    selected = select_records(
        records,
        sources,
        args.query,
        kinds=set(args.kinds) if args.kinds else None,
        areas=set(args.areas) if args.areas else None,
        max_records=args.max_records,
    )
    if args.as_json:
        payload = []
        for score, record in selected:
            compact = {
                key: record[key]
                for key in (
                    "id",
                    "kind",
                    "area",
                    "statement",
                    "status",
                    "source",
                    "freshness",
                    "last_verified_at",
                    "verified_against",
                )
            }
            compact["score"] = score
            if args.include_details and record.get("details"):
                compact["details"] = record["details"]
            payload.append(compact)
        print(json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False))
    else:
        print(
            render_selection(
                args.query,
                selected,
                sources,
                include_details=args.include_details,
                max_chars=args.max_chars,
            ),
            end="",
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
